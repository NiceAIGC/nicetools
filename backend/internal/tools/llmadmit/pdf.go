// 文泉驿微米黑（提取自 wqy-microhei.ttc，授权见 fonts/LICENSE.txt），用于 CJK 渲染。
//
//go:embed fonts/wqy-microhei-sc.ttf
var pdfFont []byte

const (
	pdfMargin = 40.0
	pdfWidth  = 595.28 // A4 宽（pt）
	pdfHeight = 841.89 // A4 高（pt）
)

type pdfWriter struct {
	pdf *gopdf.GoPdf
	y   float64
	err error
}

// renderPDF 把报告渲染为 PDF；版式与 MD 一致，每页页脚带 niceaigc 水印。
func renderPDF(rep report) ([]byte, error) {
	w := &pdfWriter{pdf: &gopdf.GoPdf{}}
	w.pdf.Start(gopdf.Config{PageSize: *gopdf.PageSizeA4})
	if err := w.pdf.AddTTFFontData("wqy", pdfFont); err != nil {
		return nil, err
	}
	w.newPage()

	w.text(fmt.Sprintf("%s 准入测试报告", rep.Standard), 16, 24)
	if rep.Masked {
		w.text("（脱敏版：已隐去测试目标地址、密钥与 request_id）", 9, 14)
	}
	w.text(fmt.Sprintf("渠道：%s    模型：%s    档位：%s    结论：%s", orDash(rep.Environment.Channel), rep.Environment.Model, rep.Environment.Tier, rep.Verdict), 10, 15)
	w.text(fmt.Sprintf("网关：%s    时段：%s ~ %s", rep.Environment.BaseURL, rep.Environment.StartedAt, rep.Environment.EndedAt), 9, 13)
	if rep.StopReason != "" {
		w.text("说明："+rep.StopReason, 9, 13)
	}
	if len(rep.Merged) > 0 {
		w.gap(4)
		w.text(fmt.Sprintf("本报告合并自 %d 次测试：", len(rep.Merged)), 10, 15)
		for _, item := range rep.Merged {
			w.text(fmt.Sprintf("· %s  档位 %s  结论 %s  完成于 %s", item.ID, item.Tier, item.Verdict, item.FinishedAt), 9, 13)
		}
	}
	if len(rep.Declarations) > 0 {
		decls := []string{}
		for k, v := range rep.Declarations {
			decls = append(decls, fmt.Sprintf("%s=%v", k, v))
		}
		w.text("能力声明："+strings.Join(decls, "，"), 9, 13)
	}

	if len(rep.Defects) > 0 {
		w.gap(6)
		w.text("缺陷清单", 13, 20)
		for _, d := range rep.Defects {
			w.text(fmt.Sprintf("[%s] %s 期望：%s；实测：%s；归因：%s", d.Level, d.CaseID, d.Expect, d.Actual, d.Attribution), 9, 13)
		}
	}

	w.gap(6)
	w.text("用例详情", 13, 20)
	for _, c := range rep.Cases {
		w.renderCase(c, rep.Masked)
	}
	return w.pdf.GetBytesPdf(), w.err
}

func (w *pdfWriter) renderCase(c caseRow, masked bool) {
	w.gap(5)
	w.text(fmt.Sprintf("%s-%s %s", c.Tier, c.CaseID, c.Name), 11, 16)
	head := fmt.Sprintf("级别：%s ｜ 结论：%s", c.LevelNote, c.Status)
	if c.HTTPStatus != 0 {
		head += fmt.Sprintf("（HTTP %d）", c.HTTPStatus)
	}
	if c.DurationMs > 0 {
		head += fmt.Sprintf("，耗时 %dms", c.DurationMs)
	}
	w.text(head, 9, 13)
	if c.Doc.Purpose != "" {
		w.text("为什么测："+c.Doc.Purpose, 9, 13)
	}
	if c.Doc.Method != "" {
		w.text("怎么测："+c.Doc.Method, 9, 13)
	}
	if c.Doc.Expect != "" {
		ref := c.Doc.Ref
		if ref != "" {
			ref = "（" + ref + "）"
		}
		w.text("预期："+c.Doc.Expect+ref, 9, 13)
	}
	if c.Summary != "" {
		w.text("实测："+c.Summary, 9, 13)
	}
	var defects []suite.Defect
	if json.Unmarshal(c.Defects, &defects) == nil {
		for _, d := range defects {
			w.text(fmt.Sprintf("缺陷 [%s] 期望：%s；实测：%s；归因：%s", d.Level, d.Expect, d.Actual, d.Attribution), 9, 13)
		}
	}
	if masked {
		return
	}
	var evidence []map[string]any
	if json.Unmarshal(c.Evidence, &evidence) != nil {
		return
	}
	for _, item := range evidence {
		label, _ := item["label"].(string)
		curl, _ := item["curl"].(string)
		w.text(fmt.Sprintf("请求（%s，curl 已脱敏）：%s", label, curl), 8, 11)
		if result, ok := item["result"].(map[string]any); ok {
			raw, _ := result["raw"].(string)
			if raw != "" {
				w.text(fmt.Sprintf("响应（HTTP %v，原文%s）：%s", result["http_status"], truncateNote(raw, 1200), truncateRunes(raw, 1200)), 8, 11)
			}
		}
	}
}

func orDash(s string) string {
	if s == "" {
		return "（未命名渠道）"
	}
	return s
}

// newPage 开新页并写页脚水印。
func (w *pdfWriter) newPage() {
	w.pdf.AddPage()
	w.y = pdfMargin
	_ = w.pdf.SetFont("wqy", "", 8)
	w.pdf.SetXY(pdfMargin, pdfHeight-28)
	_ = w.pdf.Text(fmt.Sprintf("generated by %s · %s", Watermark, Watermark))
	w.pdf.SetXY(pdfMargin, w.y)
}

func (w *pdfWriter) gap(h float64) { w.y += h }

// text 按可用宽度折行写一段文字；超页自动翻页。
// 宽度用估算（CJK≈1em、ASCII≈0.5em），避免逐字 MeasureTextWidth 的 O(n²) 开销——
// 大报告下这是导出慢的主因。
func (w *pdfWriter) text(s string, size, leading float64) {
	if w.err != nil {
		return
	}
	if err := w.pdf.SetFont("wqy", "", size); err != nil {
		w.err = err
		return
	}
	usableUnits := (pdfWidth - 2*pdfMargin) / size
	units := 0.0
	line := ""
	for _, r := range s {
		if r == '\n' {
			w.writeLine(line, leading)
			line, units = "", 0
			continue
		}
		w_ := 0.55
		if r > 0x2E7F {
			w_ = 1.0
		}
		if units+w_ > usableUnits && line != "" {
			w.writeLine(line, leading)
			line, units = string(r), w_
		} else {
			line += string(r)
			units += w_
		}
	}
	if line != "" {
		w.writeLine(line, leading)
	}
}

func (w *pdfWriter) writeLine(line string, leading float64) {
	if w.err != nil {
		return
	}
	if w.y+leading > pdfHeight-pdfMargin-20 {
		w.newPage()
	}
	w.pdf.SetXY(pdfMargin, w.y)
	if err := w.pdf.Text(line); err != nil {
		w.err = err
		return
	}
	w.y += leading
}
